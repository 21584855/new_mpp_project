"""Constrained synthesis with per-sentence attribution (ticket 20).

Facts are locked claims with anchors. The rule backend is deterministic and is
the default; a DSPy backend is optional and falls back to rules when unavailable
or when its output fails attribution checks. ``Source[x]`` markers are always
generated by code, never written by the model.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import sys
from typing import Any

from .config import Config
from .db import ensure_databases

SOURCE_RE = re.compile(r"\[Source\[(\d+)\]\]")
PROMPT_VERSION = "synth-rule-v1"
MAX_REWRITES = 1


def _prompt_hash(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]


def _meta(backend: str) -> dict[str, Any]:
    return {
        "backend": backend,
        "model": "rule-based" if backend == "rule" else os.environ.get("MPPKB_LLM_MODEL", ""),
        "temperature": 0.0,
        "prompt_hash": _prompt_hash(PROMPT_VERSION),
        "compile_version": os.environ.get("MPPKB_DSPY_COMPILE_VERSION", "none"),
    }


def _fact_anchor(fact: dict[str, Any]) -> dict[str, Any] | None:
    anchors = fact.get("anchors") or []
    if not anchors:
        return None
    anchor = anchors[0]
    if not anchor.get("doc_id") or not anchor.get("page_start"):
        return None
    return anchor


def _strip_sources(text: str) -> str:
    return SOURCE_RE.sub("", text).strip()


def _rule_sentences(facts: list[dict[str, Any]]) -> list[dict[str, Any]]:
    sentences = []
    for fact in facts:
        anchor = _fact_anchor(fact)
        if anchor is None:
            continue
        sentences.append(
            {
                "text": str(fact.get("text") or "").strip(),
                "claim_id": fact.get("claim_id"),
                "anchors": [anchor],
            }
        )
    return sentences


def _dspy_sentences(facts: list[dict[str, Any]]) -> list[dict[str, Any]] | None:
    """Optional DSPy adapter; returns None when DSPy/LM is unavailable."""
    try:
        import dspy
    except ImportError:
        return None
    try:
        class GenerateCitedResponse(dspy.Signature):
            facts = dspy.InputField(desc="locked claim facts with claim_id and text")
            sentences = dspy.OutputField(
                desc="JSON list of {text, claim_id}; never include Source markers"
            )

        module = dspy.Predict(GenerateCitedResponse)
        result = module(facts=json.dumps(facts, ensure_ascii=False))
        parsed = json.loads(result.sentences)
        if not isinstance(parsed, list):
            return None
        return parsed
    except Exception:  # noqa: BLE001 - optional backend must never break synthesis
        return None


def check_and_repair(
    sentences: list[dict[str, Any]], facts: list[dict[str, Any]]
) -> dict[str, Any]:
    allowed = {fact.get("claim_id"): fact for fact in facts}
    kept: list[dict[str, Any]] = []
    citations: list[dict[str, Any]] = []
    attribution: list[dict[str, Any]] = []
    defects: list[dict[str, Any]] = []
    rewrites = 0
    for index, sentence in enumerate(sentences, start=1):
        claim_id = sentence.get("claim_id")
        fact = allowed.get(claim_id)
        if fact is None:
            defects.append(
                {
                    "sentence": sentence.get("text"),
                    "claim_id": claim_id,
                    "reason": "unmapped_claim",
                    "action": "dropped",
                }
            )
            continue
        anchor = _fact_anchor(fact)
        if anchor is None:
            defects.append(
                {
                    "sentence": sentence.get("text"),
                    "claim_id": claim_id,
                    "reason": "missing_anchor",
                    "action": "dropped",
                }
            )
            continue
        text = str(sentence.get("text") or "").strip()
        markers = [int(match) for match in SOURCE_RE.findall(text)]
        expected = index
        stripped = _strip_sources(text)
        if markers and markers != [expected] and rewrites < MAX_REWRITES:
            rewrites += 1
            defects.append(
                {
                    "sentence": text,
                    "claim_id": claim_id,
                    "reason": "wrong_source_marker",
                    "action": "rewritten",
                    "expected_source_no": expected,
                    "found_source_no": markers,
                }
            )
        elif markers and markers != [expected]:
            defects.append(
                {
                    "sentence": text,
                    "claim_id": claim_id,
                    "reason": "wrong_source_marker",
                    "action": "dropped",
                }
            )
            continue
        final_text = f"{stripped}[Source[{expected}]]"
        kept.append(
            {
                "text": final_text,
                "claim_id": claim_id,
                "source_no": expected,
            }
        )
        citations.append(
            {
                "source_no": expected,
                "doc_id": anchor.get("doc_id"),
                "page": anchor.get("page_start"),
                "claim_id": claim_id,
            }
        )
        attribution.append(
            {"sentence": stripped, "claim_id": claim_id, "source_no": expected}
        )
    return {
        "sentences": kept,
        "citations": citations,
        "attribution": attribution,
        "defects": defects,
        "rewrites": rewrites,
    }


def synthesize(facts: list[dict[str, Any]], backend: str | None = None) -> dict[str, Any]:
    backend = (backend or os.environ.get("MPPKB_SYNTH_BACKEND", "rule")).strip().lower()
    sentences: list[dict[str, Any]] | None = None
    used = "rule"
    if backend == "dspy":
        sentences = _dspy_sentences(facts)
        if sentences is not None:
            used = "dspy"
    if sentences is None:
        sentences = _rule_sentences(facts)
        used = "rule"
    checked = check_and_repair(sentences, facts)
    answer = "；".join(item["text"] for item in checked["sentences"])
    if checked["defects"]:
        answer += f"\n注：{len(checked['defects'])} 条事实句因引用核查失败被删除或重写。"
    return {
        "ok": True,
        "backend": used,
        "answer": answer,
        "sentences": checked["sentences"],
        "citations": checked["citations"],
        "attribution": checked["attribution"],
        "defects": checked["defects"],
        "rewrites": checked["rewrites"],
        "meta": _meta(used),
    }


def _read_json(path: str | None) -> Any:
    if not path:
        return None
    return json.loads(open(path, encoding="utf-8").read())


def _emit(payload: dict[str, Any]) -> None:
    print(json.dumps(payload, ensure_ascii=False, sort_keys=True))


def run(args: Any, cfg: Config) -> int:
    command = getattr(args, "synth_command", "run")
    try:
        facts = _read_json(getattr(args, "facts", None))
    except (OSError, json.JSONDecodeError) as exc:
        _emit({"ok": False, "error": f"facts read failed: {exc}"})
        return 1
    if not isinstance(facts, list):
        _emit({"ok": False, "error": "facts must be a JSON array"})
        return 1
    if command == "run":
        payload = synthesize(facts)
    elif command == "check":
        try:
            sentences = _read_json(getattr(args, "sentences", None))
        except (OSError, json.JSONDecodeError) as exc:
            _emit({"ok": False, "error": f"sentences read failed: {exc}"})
            return 1
        if not isinstance(sentences, list):
            _emit({"ok": False, "error": "sentences must be a JSON array"})
            return 1
        checked = check_and_repair(sentences, facts)
        payload = {"ok": True, **checked, "meta": _meta("rule")}
    else:
        _emit({"ok": False, "error": f"unknown synth command: {command}"})
        return 1
    if getattr(args, "json", False):
        _emit(payload)
    else:
        print(payload.get("answer", payload))
    return 0
